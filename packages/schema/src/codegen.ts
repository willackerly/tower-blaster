import type { StructLayout } from './layout.ts';

/** WGSL declaration for a struct, with byte offsets as comments for review. */
export function wgslStruct(s: StructLayout): string {
  const lines: string[] = [];
  if (s.doc) lines.push(`// ${s.doc}`);
  lines.push(`// size ${s.size} B, align ${s.align}`);
  lines.push(`struct ${s.name} {`);
  for (const f of s.fields) {
    const doc = f.doc ? ` ${f.doc}` : '';
    lines.push(`  ${f.name}: ${f.type}, // @${f.offset}${doc}`);
  }
  lines.push('}');
  return lines.join('\n');
}

export function wgslModule(structs: StructLayout[]): string {
  const header = '// GENERATED by `pnpm codegen` from packages/schema/src/structs.ts. Do not edit.\n';
  return header + '\n' + structs.map(wgslStruct).join('\n\n') + '\n';
}
